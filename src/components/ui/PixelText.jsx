export const glyph = (ch) => (G[ch] || G[' ']).split('|');

/** `text` is upper-cased. `grid` also draws the unlit cells (used for the countdown digit). */
export default function PixelText({ text, className, cellClass, offClass, grid = false, title }) {
  const chars = [...String(text).toUpperCase()];
  const w = chars.length * 6 - 1;
  const cells = [];
  chars.forEach((ch, g) => glyph(ch).forEach((row, y) => [...row].forEach((c, x) => {
    const on = c === '#';
    if (!on && !grid) return;
    const X = g * 6 + x;
    cells.push(
      <rect key={`${g}-${x}-${y}`} x={X * 10 + 0.7} y={y * 10 + 0.7} width="8.6" height="8.6"
        className={on ? cellClass : offClass} style={on ? { '--t': `${((X * 13 + y * 29) % 23) * 28}ms` } : undefined} />,
    );
  })));
  return (
    <svg viewBox={`0 0 ${w * 10 + 4} 70`} className={className} role={title ? 'img' : undefined} aria-label={title} aria-hidden={title ? undefined : true}>
      {cells}
    </svg>
  );
}

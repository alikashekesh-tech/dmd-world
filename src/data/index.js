const FALLBACK_BRAND = { slug: 'dmd', name: 'DMD World' };
export const getBrand = (slug) => (groupBySlug[slug] ? { slug, name: groupBySlug[slug].name } : brandBySlug[slug] || FALLBACK_BRAND);
/** The brand (or group) a product is shown under, with its page: a retired group gives way to the product's main
    category (an unbranded chair filed under PC Parts shows under Gaming Furniture › Chairs & Tables). */
export function groupOf(p) {
  const g = groupBySlug[p.brand];
  if (g && isRetired(g)) { const home = homeOf(p); return home ? { name: home.name, to: home.to } : { name: FALLBACK_BRAND.name, to: '/shop' }; }
  return { name: getBrand(p.brand).name, to: catUrl(p.brand) };
}

/* ── the catalog ────────────────────────────────────────────────────────────────
   Empty until /api/v1/catalog (MySQL) arrives, or this device's cached copy of it; the app waits for one of the two
   before showing pages (CatalogGate), and no bundled data is ever used. The arrays are refilled in place; components
   that list products subscribe with useCatalog(). */
export const PRODUCTS = [];
export const productById = {};
const reindex = () => { for (const k of Object.keys(productById)) delete productById[k]; for (const p of PRODUCTS) productById[p.id] = p; };
reindex();
recountMenu(PRODUCTS);
buildDepartments(PRODUCTS);
export const getProduct = (id) => productById[id];

let version = 0;
let liveAt = 0;
const subscribers = new Set();
const changed = () => { version++; for (const fn of subscribers) fn(); };
export const catalog = {
  version: () => version,
  subscribe: (fn) => { subscribers.add(fn); return () => subscribers.delete(fn); },
  /** When the catalog on screen was generated by the server (0 before the first one). */
  liveAt: () => liveAt,
};
/** What the home page shows (the owner's section order, hand-picked items, banners), from the catalog.
    `sections` stays null until the first catalog, so the home page shows its built-in order. */
export const HOMEPAGE = { sections: null, picks: {}, banners: [], announcement: null };
/** The public store settings (defaults until the first catalog). */
export const STORE = { name: 'DMD World', couponsEnabled: true, reviewsEnabled: true, deliveryFee: null, menu: DEFAULT_MENU, assistant: false };
/**
 * What delivery costs in dollars, as the server charges it: 0 for pickup; for delivery each product's own price or
 * else the store's, and an order (delivered once) pays the highest. null = no price known: DMD confirms it later.
 * With no products, the store's price.
 */
export const deliveryFee = (method = 'delivery', products = []) => {
  if (method !== 'delivery') return 0;
  const fees = products.length ? products.map((p) => p?.deliveryFee ?? STORE.deliveryFee) : [STORE.deliveryFee];
  const known = fees.filter((f) => f != null);
  return known.length ? Math.max(...known) : null;
};
export const deliveryLabel = (fee) => (fee == null ? 'Confirmed on order' : fee > 0 ? money(fee) : 'Free');

/* Banners carry their end time; one whose end has passed is dropped here, even from an older copy of the catalog, and a
   timer drops the next one to end at its exact moment while the page stays open. */
const running = (b) => b && (!b.ends_at || Date.parse(b.ends_at) > Date.now());
let bannerTimer = null;
function expireBanners() {
  clearTimeout(bannerTimer);
  const banners = HOMEPAGE.banners.filter(running);
  const announcement = running(HOMEPAGE.announcement) ? HOMEPAGE.announcement : null;
  const gone = banners.length !== HOMEPAGE.banners.length || announcement !== HOMEPAGE.announcement;
  Object.assign(HOMEPAGE, { banners, announcement });
  const next = Math.min(...[...banners, announcement].filter((b) => b?.ends_at).map((b) => Date.parse(b.ends_at)));
  if (Number.isFinite(next) && next - Date.now() < 864e5) bannerTimer = setTimeout(() => { if (expireBanners()) changed(); }, Math.max(0, next - Date.now()) + 50);
  return gone;
}
/** Hides the banners and the announcement (shown again by the next catalog the server confirms). */
export function withdrawBanners() {
  if (!HOMEPAGE.banners.length && !HOMEPAGE.announcement) return;
  clearTimeout(bannerTimer);
  Object.assign(HOMEPAGE, { banners: [], announcement: null });
  changed();
}

function applyStore(home = {}, store = {}) {
  Object.assign(HOMEPAGE, {
    sections: Array.isArray(home.sections) ? home.sections : null, picks: home.picks && typeof home.picks === 'object' ? home.picks : {},
    banners: Array.isArray(home.banners) ? home.banners : [], announcement: home.announcement || null,
  });
  expireBanners();
  if (store.contact_phone) Object.assign(CONTACT, { phone: store.contact_phone, tel: store.contact_phone.replace(/[^\d+]/g, '') });
  if (store.contact_email) CONTACT.email = store.contact_email;
  Object.assign(STORE, {
    name: store.store_name || STORE.name, couponsEnabled: store.coupons_enabled !== false, reviewsEnabled: store.reviews_enabled !== false,
    deliveryFee: store.delivery_fee == null || Number.isNaN(Number(store.delivery_fee)) ? null : Number(store.delivery_fee),
    menu: Array.isArray(store.menu_links) ? store.menu_links.filter((k) => MENU_LINKS[k]) : DEFAULT_MENU,
    assistant: store.assistant_enabled === true, // the shopping assistant in the contact button
  });
  configureAnalytics(store.ga4_measurement_id || null); // GA4 stays off without an ID (and the visitor's consent)
}

/** Swaps in /api/v1/catalog ({ generated_at, products, categories, brands, homepage, store }) from MySQL. */
export function applyCatalog(data) {
  if (!data || !Array.isArray(data.products) || !Array.isArray(data.categories)) return false;
  setCategories(data.categories.map((c) => [c.id, c.name, c.slug, c.parent_id || 0, 0, c.brand_id ?? null]));
  applyTaxonomy({ categories: data.categories, brands: data.brands || [] });
  const brandSlugs = new Map((data.brands || []).map((b) => [b.id, b.slug]));
  const ctx = { brandSlug: (id) => brandSlugs.get(id), offersId: NEW_OFFERS.id ?? null };
  const next = [];
  for (const p of data.products) { try { next.push(fromApi(p, ctx)); } catch { /* skip a malformed product */ } }
  PRODUCTS.splice(0, PRODUCTS.length, ...next);
  reindex(); recountMenu(PRODUCTS); buildDepartments(PRODUCTS);
  applyStore(data.homepage, data.store);
  liveAt = Date.parse(data.generated_at) || Date.now();
  changed();
  return true;
}

export const isNew = (p) => p.tag === 'new' || (Date.now() - new Date(p.date).getTime()) < 1000 * 60 * 60 * 24 * 75;
export const inStock = (p) => p.stock !== 'out';
/** How many of a product one cart may hold in all: its stock when tracked, no stock limit when not (checkout enforces the same). */
export const purchaseLimit = (p) => (!p ? Infinity : p.stock === 'out' ? 0 : p.maxQty ?? Infinity);
/** The same for one variant of a variable product (its own stock). */
export const variantLimit = (v) => (!v ? 0 : v.stock === 'out' ? 0 : v.maxQty ?? Infinity);

// ── search ─────────────────────────────────────────────────────────────────────
const fold = (s) => String(s).toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '');
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
/** Every word must match; names that start with (or contain a word starting with) the query rank first, in stock before sold out. */
export function search(q, limit = 8) {
  const terms = fold(q).split(/\s+/).filter(Boolean);
  if (!terms.length) return [];
  const hits = [];
  for (const p of PRODUCTS) {
    if (!terms.every((t) => p.search.includes(t))) continue;
    const name = fold(p.name);
    let score = p.stock === 'out' ? 0 : 3;
    for (const t of terms) score += name.startsWith(t) ? 6 : new RegExp(`(^|[^a-z0-9])${esc(t)}`).test(name) ? 4 : name.includes(t) ? 2 : 0;
    hits.push([score, p]);
  }
  return hits.sort((a, b) => b[0] - a[0] || b[1].sold - a[1].sold).slice(0, limit).map((h) => h[1]);
}

// ── filtering ──────────────────────────────────────────────────────────────────
export const SORTS = [
  { key: 'featured', label: 'Featured' },
  { key: 'best', label: 'Best Selling' },
  { key: 'newest', label: 'Newest' },
  { key: 'price-asc', label: 'Price: Low to High' },
  { key: 'price-desc', label: 'Price: High to Low' },
  { key: 'rating', label: 'Highest Rated' },
];
export function sortProducts(list, key) {
  const a = [...list];
  const score = (p) => p.sold * 0.6 + p.r * p.n * 0.4 + (p.tag === 'best' ? 5000 : 0) - (p.stock === 'out' ? 1e6 : 0);
  switch (key) {
    case 'best': return a.sort((x, y) => y.sold - x.sold);
    case 'newest': return a.sort((x, y) => new Date(y.date) - new Date(x.date));
    case 'price-asc': return a.sort((x, y) => x.price - y.price);
    case 'price-desc': return a.sort((x, y) => y.price - x.price);
    case 'rating': return a.sort((x, y) => y.r - x.r || y.n - x.n);
    default: return a.sort((x, y) => score(y) - score(x));
  }
}

/** The values a product offers for a facet key (all facet keys incl. core ones). */
export function facetValues(p, key) {
  switch (key) {
    case 'brand': return p.brandId != null ? [p.brand] : []; // the brands the store lists, not a product's category group
    case 'type': return [p.cat];
    case 'platform': return [...p.compat, ...(p.multi ? ['multi'] : [])];
    case 'conn': return p.conn ? (p.conn === 'Wired / Wireless' ? ['Wired', 'Wireless'] : [p.conn]) : [];
    case 'color': return p.colorFamilies;
    case 'stock': return [p.stock === 'out' ? 'out' : 'in'];
    case 'condition': { const c = conditionOf(p); return c ? [c.key] : []; }
    default: return p.facets[key] || [];
  }
}
export const platformLabel = (k) => (k === 'multi' ? 'Multi-platform' : COMPAT[k]?.label || k);

/** Filter state: { brand:[one], platform:[one], ..., price:[min,max]|null, rating:number|0, stock:['in'|'out'], cat }
    (the category, `cat`, is applied by ProductBrowser from its own options). */
export function applyFilters(list, f, skipKey) {
  const terms = f.q ? fold(f.q).split(/\s+/).filter(Boolean) : null;
  return list.filter((p) => {
    for (const key of Object.keys(f)) {
      if (key === skipKey || key === 'price' || key === 'rating' || key === 'q' || key === 'cat') continue;
      const want = f[key];
      if (!want || !want.length) continue;
      const have = facetValues(p, key);
      if (!want.some((w) => have.includes(w))) return false;
    }
    if (skipKey !== 'price' && f.price) { if (p.price < f.price[0] || p.price > f.price[1]) return false; }
    if (skipKey !== 'rating' && f.rating && p.r < f.rating) return false;
    if (terms && !terms.every((t) => p.search.includes(t))) return false;
    return true;
  });
}

/** Options for one facet with counts (counts respect all other active filters). */
export function facetOptions(base, f, key) {
  const pool = applyFilters(base, f, key);
  const counts = new Map();
  const universe = new Map();
  for (const p of base) for (const v of facetValues(p, key)) universe.set(v, (universe.get(v) || 0));
  for (const p of pool) for (const v of facetValues(p, key)) counts.set(v, (counts.get(v) || 0) + 1);
  let opts = [...universe.keys()].map((value) => ({ value, count: counts.get(value) || 0 }));
  if (key === 'platform') {
    const order = [...COMPAT_ORDER, 'multi'];
    opts.sort((a, b) => order.indexOf(a.value) - order.indexOf(b.value));
  } else if (key === 'brand') opts.sort((a, b) => getBrand(a.value).name.localeCompare(getBrand(b.value).name));
  else if (key === 'color') opts.sort((a, b) => b.count - a.count);
  else if (key === 'condition') opts.sort((a, b) => (CONDITION_ORDER.indexOf(a.value) + 1 || 99) - (CONDITION_ORDER.indexOf(b.value) + 1 || 99));
  else opts.sort((a, b) => String(a.value).localeCompare(String(b.value), undefined, { numeric: true }));
  return opts;
}

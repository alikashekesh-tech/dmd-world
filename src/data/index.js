export function compatLabels(p, max = 4) {
  if (p.universal && !p.compat.length) return { items: ['Universal'], more: 0 };
  const items = p.compat.map((k) => COMPAT[k].short);
  return { items: items.slice(0, max), more: Math.max(0, items.length - max) };
}
